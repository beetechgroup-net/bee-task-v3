-- 1. Create table task_statuses
CREATE TABLE task_statuses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    color VARCHAR(32) NOT NULL DEFAULT '#71717a',
    position INT NOT NULL DEFAULT 0,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    is_canceled BOOLEAN NOT NULL DEFAULT FALSE,
    organization_id BIGINT NOT NULL,
    deleted_at TIMESTAMP,
    CONSTRAINT fk_task_statuses_organization
        FOREIGN KEY (organization_id) REFERENCES organizations (id)
);

CREATE INDEX idx_task_statuses_organization_id ON task_statuses (organization_id);
CREATE UNIQUE INDEX uk_task_statuses_org_name ON task_statuses (organization_id, lower(name)) WHERE deleted_at IS NULL;

