-- 3. Ensure any tasks without organization_id receive first organization
UPDATE tasks
SET organization_id = (SELECT id FROM organizations ORDER BY id ASC LIMIT 1)
WHERE organization_id IS NULL;

-- 4. Add status_id to tasks and drop old enum constraint
ALTER TABLE tasks ADD COLUMN status_id BIGINT REFERENCES task_statuses(id);
CREATE INDEX idx_tasks_status_id ON tasks (status_id);

ALTER TABLE tasks DROP CONSTRAINT IF EXISTS chk_tasks_status;

-- 5. Backfill status_id and update status column to match name
UPDATE tasks t
SET status_id = s.id,
    status = s.name
FROM task_statuses s
WHERE s.organization_id = t.organization_id
  AND (
    (t.status = 'NOT_STARTED' AND s.name = 'A Fazer') OR
    (t.status = 'IN_PROGRESS' AND s.name = 'Em Andamento') OR
    (t.status = 'COMPLETED' AND s.name = 'Concluído') OR
    (t.status = 'CANCELED' AND s.name = 'Cancelado')
  );

-- For any remaining tasks, link to the organization's default status
UPDATE tasks t
SET status_id = s.id,
    status = s.name
FROM task_statuses s
WHERE s.organization_id = t.organization_id
  AND s.is_default = TRUE
  AND t.status_id IS NULL;
